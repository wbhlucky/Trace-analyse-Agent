# ``embedding`` is deliberately absent from ``_TABLES``: its type depends on
# whether pgvector is installed, and a corpus must not silently switch column
# types under an existing set of vectors.
_EMBEDDING_TABLES = ("memories", "episodes")


def embedding_column_type(*, pgvector: bool) -> str:
    """Column type for stored vectors.

    Unbounded ``vector`` rather than ``vector(n)``: the width is a property of the
    embedding recipe, which is configuration, and a corpus whose configured
    dimension changed must keep reading its old rows until
    :meth:`PostgresStore.vector_index` rewrites them. Bounding the column here
    would turn a config edit into a write error.
    """
    return "vector" if pgvector else "BYTEA"


def pgvector_available(execute: Execute) -> bool:
    """Whether the ``vector`` extension is usable in this database.

    Installing it is attempted first because a server that has the binaries but
    not the extension is the common case, and ``CREATE EXTENSION IF NOT EXISTS``
    is idempotent. Failing to create it - no superuser, no package - is not an
    error: the caller falls back to BYTEA and an exact cosine, which is what the
    SQLite adapter already does.
    """
    try:
        execute("CREATE EXTENSION IF NOT EXISTS vector", ())
    except Exception:
        pass
    try:
        rows = execute(
            "SELECT 1 FROM pg_extension WHERE extname = 'vector' LIMIT 1", ()
        )
    except Exception:
        return False
    return bool(rows)


def _embedding_column_is_vector(execute: Execute) -> bool | None:
    """Whether ``memories.embedding`` is really a pgvector column, or ``None``.

    :func:`apply_schema` picks the column type from the extension probe, but
    ``ADD COLUMN IF NOT EXISTS`` never rewrites a column that already exists: a
    corpus created before pgvector was installed keeps its ``BYTEA`` embedding
    even once ``CREATE EXTENSION`` would succeed. The store's runtime behaviour
    keys off the *column* type, not the extension - the ``::vector`` cast in
    :meth:`PostgresStore.set_embedding` and the ``<=>`` pushdown in
    :meth:`PostgresStore.vector_search` both assume a ``vector`` column - so
    reporting ``True`` over a ``BYTEA`` column makes every write and recall
    silently fail. This reads the column back through ``to_regclass``, which
    resolves via ``search_path`` exactly as the store's own unqualified queries
    do. ``None`` means "could not tell" (no such column, a catalog query that
    failed), and the caller then keeps its probe-derived answer rather than
    guessing.
    """
    try:
        rows = execute(
            "SELECT t.typname FROM pg_attribute a "
            "JOIN pg_class c ON c.oid = a.attrelid "
            "JOIN pg_type t ON t.oid = a.atttypid "
            "WHERE c.oid = to_regclass('memories') AND a.attname = 'embedding'",
            (),
        )
    except Exception:
        return None
    if not rows:
        return None
    return str(rows[0][0] or "").lower().startswith("vector")


def apply_schema(
    execute: Execute,
    *,
    schema: str = "public",
    pgvector: bool | None = None,
) -> bool:
    """Create the tables, indexes and embedding columns; returns pgvector state.

    Idempotent, so it runs on every new connection and doubles as the migration
    entry point. Statements are executed one at a time rather than as a script:
    PostgreSQL has no ``executescript``, and one failing statement must not abort
    the rest of the DDL - an index that cannot be created still leaves a working
    (if slower) corpus, which is the same trade :func:`schema.apply_schema` makes.
    """
    if schema and schema != "public":
        _quiet(execute, f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
    vectors = pgvector
    if vectors is None:
        vectors = pgvector_available(execute)
    for statement in _statements(_TABLES):
        _quiet(execute, statement)
    for table, column, fragment in _ADDITIVE_COLUMNS:
        _quiet(
            execute,
            f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {fragment}",
        )
    column_type = embedding_column_type(pgvector=bool(vectors))
    for table in _EMBEDDING_TABLES:
        _quiet(
            execute,
            f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS embedding {column_type}",
        )
    if pgvector is None:
        # The probe answered "is the extension installed"; the store acts on
        # "are vectors stored as one". They disagree whenever a pre-pgvector
        # BYTEA corpus meets a server that has since gained the extension, and
        # the column is the truth - so trust it over the probe when it is
        # readable. An explicit ``pgvector`` flag is a caller that already knows
        # and must not pay for a second look, so this reconciles only the probe.
        actual = _embedding_column_is_vector(execute)
        if actual is not None:
            vectors = actual
    _quiet(
        execute,
        "INSERT INTO store_meta (key, value) VALUES ('schema_version', %s) "
        "ON CONFLICT (key) DO UPDATE SET value = excluded.value",
        (str(PG_SCHEMA_VERSION),),
    )
    return bool(vectors)


def schema_version(execute: Execute) -> int:
    """Version this database was stamped with, or 0 for an uninitialised one."""
    try:
        rows = execute(
            "SELECT value FROM store_meta WHERE key = 'schema_version'", ()
        )
    except Exception:
        return 0
    if not rows:
        return 0
    try:
        return int(rows[0][0])
    except (TypeError, ValueError, IndexError):
        return 0


def server_version(execute: Execute) -> str:
    """Human-readable server version, for ``memory stats`` diagnostics."""
    try:
        rows = execute("SELECT version()", ())
    except Exception:
        return ""
    if not rows:
        return ""
    return str(rows[0][0] or "")


def pgvector_literal(vector: Sequence[float]) -> str:
    """Render a vector as the text pgvector casts from (``'[1.0,2.0]'``).

    ``repr``-style float formatting rather than a fixed precision: the value has
    already been through the provider and will be narrowed to ``float4`` by the
    column, and rounding here as well would make the stored vector differ from
    the one the BYTEA path stores for the same input.
    """
    return "[" + ",".join(str(float(item)) for item in vector) + "]"


def parse_pgvector_literal(raw: Any) -> list[float]:
    """Inverse of :func:`pgvector_literal`, tolerant of anything unusable.

    Reads come back as text (``embedding::text``) because no driver knows the
    ``vector`` type without an extra registration step, and an adapter that
    needed one would fail on a psycopg build that predates it. As with
    :func:`~trace_agent.memory.embedding.ports.unpack_vector`, a value that
    cannot be parsed means "treat this record as unembedded", never an error.
    """
    if raw is None:
        return []
    if isinstance(raw, (bytes, bytearray, memoryview)):
        try:
            raw = bytes(raw).decode("utf-8")
        except UnicodeDecodeError:
            return []
    text = str(raw).strip()
    if not text:
        return []
    if text.startswith("[") and text.endswith("]"):
        text = text[1:-1]
    if not text.strip():
        return []
    out: list[float] = []
    for part in text.split(","):
        try:
            out.append(float(part))
        except (TypeError, ValueError):
            return []
    return out


def tsquery_match(text: str) -> str | None:
    """Build an OR'd ``tsquery`` expression, or ``None`` when there are no tokens.

    The PostgreSQL counterpart of :func:`~trace_agent.memory.store.fts.fts_match`,
    and it matters that the two answer the same question: ``tsquery`` ANDs its
    terms too, so ``'白屏 耗时'`` written as a plain query would demand both and
    return nothing for a memory mentioning only one. Explicit ``|`` makes the
    pool "shares at least one token with the query", which is the superset
    property :class:`~trace_agent.memory.recall.RecallService` relies on to skip
    a full scan.

    Tokens come from the same :func:`~trace_agent.memory.text.tokenize` the FTS5
    body is built with, so the indexed bigrams and the queried bigrams are the
    same units on both stores. Each is single-quoted, which is tsquery's lexeme
    literal and also the only escaping the syntax needs.
    """
    tokens = dict.fromkeys(tokenize(text))
    if not tokens:
        return None
    return " | ".join(
        "'" + str(token).replace("'", "''") + "'" for token in tokens
    )


def _statements(script: str) -> list[str]:
    """Split DDL on ``;`` at end of line, dropping comments and blanks."""
    out: list[str] = []
    for chunk in script.split(";\n"):
        lines = [
            line
            for line in chunk.splitlines()
            if line.strip() and not line.strip().startswith("--")
        ]
        statement = "\n".join(lines).strip().rstrip(";").strip()
        if statement:
            out.append(statement)
    return out


def _quiet(execute: Execute, sql: str, params: Sequence[Any] = ()) -> None:
    """Run one DDL statement, ignoring a failure.

    Used only for schema setup, where every statement is either ``IF NOT EXISTS``
    or additive. The alternative - raising - would make a missing index permission
    or an absent pgvector build take the whole memory corpus offline, and section
    13 asks for degradation instead.
    """
    try:
        execute(sql, params)
    except Exception:
        return


