"""PostgreSQL dialect for the memory schema.

Section 4 of ``docs/memory-optimization-plan.md`` promises one table shape for
SQLite and Postgres, and this module is where that promise is kept: the columns,
keys and semantics are the ones :mod:`trace_agent.memory.store.schema` defines,
translated only where the two engines genuinely differ.

The differences that matter, and why each is safe:

* **No ``rowid``.** SQLite keys its FTS5 side tables by the parent row's implicit
  integer id. Postgres has no equivalent that survives an ``ON CONFLICT DO
  UPDATE`` (``ctid`` moves), so the side tables are keyed by
  ``(namespace, memory_id)`` instead - which is what section 8 says is the real
  identity of a record anyway.
* **``tsvector`` instead of FTS5.** Ranking is ``ts_rank`` rather than bm25, and
  the adapter negates it so "more negative is better" holds on both stores. The
  indexed text is the *same* bigram-expanded body from
  :mod:`trace_agent.memory.store.fts`, which is what makes CJK recall work: the
  ``simple`` configuration does no linguistic analysis, so it tokenises the
  already-segmented body on whitespace exactly as ``unicode61`` does.
* **``scope`` is JSONB**, because it is filtered on. Every other JSON column
  stays TEXT: those are read back wholesale into a model, and JSONB would only
  add a parse on write.
* **``embedding`` is ``vector`` when pgvector is installed and BYTEA otherwise.**
  The choice is made when the schema is applied and never changes under a corpus;
  a BYTEA column keeps working with an exact Python cosine, which is precisely
  what the SQLite adapter does, so semantic recall degrades to the same behaviour
  rather than disappearing.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from typing import Any

from trace_agent.memory.store.schema import SCHEMA_VERSION
from trace_agent.memory.text import tokenize

#: Executes one statement. The adapter passes a driver-agnostic shim so this
#: module never imports psycopg2/psycopg, which keeps it unit-testable without a
#: server and keeps the optional dependency optional.
Execute = Callable[[str, Sequence[Any]], Any]

# Both stores describe the same model, so they share one version number. A
# PostgreSQL corpus stamped with a different version than the SQLite one would
# make ``memory migrate`` treat a portable snapshot as foreign.
PG_SCHEMA_VERSION = SCHEMA_VERSION

# Columns added after a table shipped, mirroring ``schema._ADDITIVE_COLUMNS``
# for the ownership columns of schema version 3. The embedding columns are
# handled separately below because their type depends on pgvector being
# installed; these are plain ``TEXT`` and therefore one uniform loop.
#
# PostgreSQL has ``ADD COLUMN IF NOT EXISTS``, so the ``PRAGMA table_info``
# probe the SQLite dialect needs is not required here, and a statement that fails
# (a read-only replica, a missing privilege) degrades through ``_quiet`` to a
# corpus without the column rather than aborting the DDL.
_ADDITIVE_COLUMNS: tuple[tuple[str, str, str], ...] = (
    ("episodes", "session_id", "TEXT"),
    ("episodes", "project_id", "TEXT"),
    ("sessions", "agent_id", "TEXT"),
    ("sessions", "user_id", "TEXT"),
    ("sessions", "project_id", "TEXT"),
    ("memory_versions", "from_trust", "TEXT"),
)

